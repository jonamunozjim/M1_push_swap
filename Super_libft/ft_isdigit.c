#include "super_libft.h"

/*
Checks if a character is a number.
Returns 1 if it is a digit, and 0 if it is not.
*/

int	ft_isdigit(int c)
{
	if (c >= '0' && c <= '9')
	{
		return (1);
	}
	else
		return (0);
}
