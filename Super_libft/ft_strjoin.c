#include "super_libft.h"

/*
Joins two strings safely.
Copies the source string to the end of the destination string using strlcat.
first uses strlcpy to copy s1 in the empty memory and then joins with strlcat.
*/

char	*ft_strjoin(char const *s1, char const *s2)
{
	size_t	len;
	char	*str;

	if (s1 == NULL || s2 == NULL)
		return (NULL);
	len = ft_strlen(s1) + ft_strlen(s2) + 1;
	str = malloc(sizeof(char) * len);
	if (str == NULL)
		return (NULL);
	ft_strlcpy(str, s1, len);
	ft_strlcat(str, s2, len);
	return (str);
}
