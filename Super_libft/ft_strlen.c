#include "super_libft.h"

/*
Calculates the length of a string.
Counts each character one by one until it finds \0.
Returns the total number.
*/

size_t	ft_strlen(const char *str)
{
	size_t	i;

	i = 0;
	while (str[i] != '\0')
	{
		i++;
	}
	return (i);
}
